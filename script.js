  document.querySelector('#profile .title').innerText = t.heroTitle;
  document.querySelector('.hero-description-text p').innerText = t.heroDesc;
  const heroBtnServices = document.querySelector('#profile .btn-color-2');
  if (heroBtnServices) heroBtnServices.innerText = t.btnServices;
  const heroBtnWork = document.querySelector('#profile .btn-color-1');
  if (heroBtnWork) heroBtnWork.innerText = t.btnWork;

  // Services Section — NEW CARD STRUCTURE
  document.querySelector('#about .title').innerText = t.servicesTitle;
